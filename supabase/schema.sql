create table if not exists public.perfiles(
  id uuid primary key references auth.users(id) on delete cascade,
  nombre_completo text not null,
  rol public.rol_usuario not null default 'mesero',
  activo boolean not null default true,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);
create table if not exists public.mesas(
  id bigint generated by default as identity primary key,
  numero integer not null unique check(numero>0),
  nombre text,
  capacidad integer check(capacidad is null or capacidad>0),
  activa boolean not null default true,
  creada_en timestamptz not null default now()
);
create table if not exists public.categorias(
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  descripcion text,
  orden integer not null default 0,
  activa boolean not null default true,
  creada_en timestamptz not null default now()
);
create table if not exists public.productos(
  id bigint generated by default as identity primary key,
  categoria_id bigint references public.categorias(id) on delete set null,
  nombre text not null,
  descripcion text,
  precio numeric(10,2) not null check(precio>=0),
  imagen_url text,
  disponible boolean not null default true,
  activo boolean not null default true,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);
create table if not exists public.pedidos(
  id uuid primary key default gen_random_uuid(),
  ticket text not null unique,
  token_consulta text not null unique,
  tipo public.tipo_pedido not null default 'mesa',
  mesa_id bigint references public.mesas(id) on delete set null,
  cliente_nombre text,
  cliente_telefono text,
  direccion_entrega text,
  estado public.estado_pedido not null default 'pendiente',
  estado_pago public.estado_pago not null default 'pendiente',
  forma_pago public.forma_pago,
  subtotal numeric(10,2) not null default 0,
  recargo numeric(10,2) not null default 0,
  descuento numeric(10,2) not null default 0,
  total numeric(10,2) not null default 0,
  observaciones text,
  creado_por uuid references public.perfiles(id) on delete set null,
  origen text not null default 'menu_publico' check(origen in('menu_publico','mesero','caja','administrador')),
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now(),
  cerrado_en timestamptz,
  check(tipo<>'mesa' or mesa_id is not null)
);
create table if not exists public.detalle_pedido(
  id bigint generated by default as identity primary key,
  pedido_id uuid not null references public.pedidos(id) on delete cascade,
  producto_id bigint references public.productos(id) on delete set null,
  producto_nombre text not null,
  cantidad integer not null check(cantidad>0),
  precio_unitario numeric(10,2) not null check(precio_unitario>=0),
  subtotal numeric(10,2) not null check(subtotal>=0),
  observaciones text,
  creado_en timestamptz not null default now()
);
create table if not exists public.historial_estado_pedido(
  id bigint generated by default as identity primary key,
  pedido_id uuid not null references public.pedidos(id) on delete cascade,
  estado_anterior public.estado_pedido,
  estado_nuevo public.estado_pedido not null,
  cambiado_por uuid references public.perfiles(id) on delete set null,
  observacion text,
  cambiado_en timestamptz not null default now()
);
create table if not exists public.pagos(
  id uuid primary key default gen_random_uuid(),
  pedido_id uuid not null references public.pedidos(id) on delete restrict,
  monto numeric(10,2) not null check(monto>0),
  forma_pago public.forma_pago not null,
  referencia text,
  registrado_por uuid references public.perfiles(id) on delete set null,
  registrado_en timestamptz not null default now(),
  anulado boolean not null default false,
  anulado_por uuid references public.perfiles(id) on delete set null,
  anulado_en timestamptz,
  motivo_anulacion text
);

