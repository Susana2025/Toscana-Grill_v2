create or replace function public.crear_pedido(
 p_tipo text,p_mesa_id bigint,p_cliente_nombre text,p_cliente_telefono text,
 p_direccion_entrega text,p_observaciones text,p_items jsonb
) returns jsonb language plpgsql security definer set search_path='' as $$
declare
 v_id uuid; v_ticket text; v_token text; v_tipo public.tipo_pedido; v_item jsonb;
 v_prod record; v_pid bigint; v_qty integer; v_sub numeric(10,2); v_total numeric(10,2):=0;
 v_user uuid; v_origin text:='menu_publico';
begin
 v_tipo:=p_tipo::public.tipo_pedido;
 if p_items is null or jsonb_typeof(p_items)<>'array' or jsonb_array_length(p_items)=0 then raise exception 'El pedido debe contener productos.'; end if;
 if v_tipo='mesa' and not exists(select 1 from public.mesas where id=p_mesa_id and activa=true) then raise exception 'Mesa no válida.'; end if;
 if v_tipo='delivery' and nullif(trim(coalesce(p_direccion_entrega,'')),'') is null then raise exception 'Dirección requerida.'; end if;
 select id into v_user from public.perfiles where id=auth.uid() and activo=true;
 if v_user is not null then select case rol when 'mesero' then 'mesero' when 'caja' then 'caja' when 'administrador' then 'administrador' else 'menu_publico' end into v_origin from public.perfiles where id=v_user; end if;
 loop
  v_ticket:='TG-'||to_char(timezone('America/Guayaquil',now()),'YYYYMMDD')||'-'||upper(substr(replace(gen_random_uuid()::text,'-',''),1,6));
  exit when not exists(select 1 from public.pedidos where ticket=v_ticket);
 end loop;
 v_token:=replace(gen_random_uuid()::text,'-','')||replace(gen_random_uuid()::text,'-','');
 insert into public.pedidos(ticket,token_consulta,tipo,mesa_id,cliente_nombre,cliente_telefono,direccion_entrega,observaciones,creado_por,origen)
 values(v_ticket,v_token,v_tipo,case when v_tipo='mesa' then p_mesa_id end,nullif(trim(coalesce(p_cliente_nombre,'')),''),
 nullif(trim(coalesce(p_cliente_telefono,'')),''),case when v_tipo='delivery' then nullif(trim(coalesce(p_direccion_entrega,'')),'') end,
 nullif(trim(coalesce(p_observaciones,'')),''),v_user,v_origin) returning id into v_id;
 for v_item in select value from jsonb_array_elements(p_items) loop
   v_pid:=(v_item->>'producto_id')::bigint; v_qty:=(v_item->>'cantidad')::integer;
   if v_qty is null or v_qty<=0 or v_qty>100 then raise exception 'Cantidad no válida.'; end if;
   select id,nombre,precio into v_prod from public.productos where id=v_pid and activo=true and disponible=true;
   if not found then raise exception 'Producto no disponible: %',v_pid; end if;
   v_sub:=round(v_prod.precio*v_qty,2);
   insert into public.detalle_pedido(pedido_id,producto_id,producto_nombre,cantidad,precio_unitario,subtotal,observaciones)
   values(v_id,v_prod.id,v_prod.nombre,v_qty,v_prod.precio,v_sub,nullif(trim(coalesce(v_item->>'observaciones','')),''));
   v_total:=v_total+v_sub;
 end loop;
 update public.pedidos set subtotal=v_total,total=v_total where id=v_id;
 return jsonb_build_object('pedido_id',v_id,'ticket',v_ticket,'token_consulta',v_token,'estado','pendiente','total',v_total);
end $$;
revoke all on function public.crear_pedido(text,bigint,text,text,text,text,jsonb) from public;
grant execute on function public.crear_pedido(text,bigint,text,text,text,text,jsonb) to anon,authenticated;

create or replace function public.listar_pedidos_activos()
returns table(pedido_id uuid,ticket text,tipo public.tipo_pedido,mesa_numero integer,mesa_nombre text,
 cliente_nombre text,estado public.estado_pedido,estado_pago public.estado_pago,total numeric,cantidad_items bigint,
 creado_por uuid,creado_por_nombre text,creado_en timestamptz,actualizado_en timestamptz)
language plpgsql security definer stable set search_path='' as $$
declare uid uuid; r public.rol_usuario;
begin
 select id,rol into uid,r from public.perfiles where id=auth.uid() and activo=true;
 if uid is null then raise exception 'Usuario no autenticado.'; end if;
 return query select p.id,p.ticket,p.tipo,m.numero,m.nombre,p.cliente_nombre,p.estado,p.estado_pago,p.total,
 coalesce(sum(d.cantidad),0)::bigint,p.creado_por,pr.nombre_completo,p.creado_en,p.actualizado_en
 from public.pedidos p left join public.mesas m on m.id=p.mesa_id left join public.detalle_pedido d on d.pedido_id=p.id
 left join public.perfiles pr on pr.id=p.creado_por
 where p.estado not in('cerrado','cancelado') and (r in('administrador','caja','cocina') or (r='mesero' and p.creado_por=uid))
 group by p.id,m.numero,m.nombre,pr.nombre_completo order by p.creado_en;
end $$;
revoke all on function public.listar_pedidos_activos() from public;
grant execute on function public.listar_pedidos_activos() to authenticated;

create or replace function public.obtener_detalle_pedido(p_pedido_id uuid) returns jsonb
language plpgsql security definer stable set search_path='' as $$
declare uid uuid;r public.rol_usuario;p record;items jsonb;
begin
 select id,rol into uid,r from public.perfiles where id=auth.uid() and activo=true;
 if uid is null then raise exception 'Usuario no autenticado.'; end if;
 select pe.*,m.numero mesa_numero,m.nombre mesa_nombre into p from public.pedidos pe left join public.mesas m on m.id=pe.mesa_id where pe.id=p_pedido_id;
 if not found then raise exception 'Pedido no encontrado.'; end if;
 if r='mesero' and p.creado_por is distinct from uid then raise exception 'Acceso denegado.'; end if;
 select coalesce(jsonb_agg(jsonb_build_object('producto',producto_nombre,'cantidad',cantidad,'precio_unitario',precio_unitario,'subtotal',subtotal,'observaciones',observaciones) order by id),'[]'::jsonb)
 into items from public.detalle_pedido where pedido_id=p_pedido_id;
 return jsonb_build_object('pedido_id',p.id,'ticket',p.ticket,'tipo',p.tipo,'mesa',case when p.tipo='mesa' then jsonb_build_object('numero',p.mesa_numero,'nombre',p.mesa_nombre) end,
 'estado',p.estado,'estado_pago',p.estado_pago,'total',p.total,'observaciones',p.observaciones,'creado_en',p.creado_en,'detalle',items);
end $$;
revoke all on function public.obtener_detalle_pedido(uuid) from public;
grant execute on function public.obtener_detalle_pedido(uuid) to authenticated;

create or replace function public.resumen_diario(p_fecha date default null) returns jsonb
language plpgsql security definer stable set search_path='' as $$
declare uid uuid;r public.rol_usuario;f date;tot int;act int;cerr int;can int;ventas numeric;pagado numeric;
begin
 select id,rol into uid,r from public.perfiles where id=auth.uid() and activo=true;
 if uid is null or r not in('administrador','caja') then raise exception 'Acceso denegado.'; end if;
 f:=coalesce(p_fecha,timezone('America/Guayaquil',now())::date);
 select count(*)::int,count(*) filter(where estado not in('cerrado','cancelado'))::int,count(*) filter(where estado='cerrado')::int,
 count(*) filter(where estado='cancelado')::int,coalesce(sum(total) filter(where estado<>'cancelado'),0)
 into tot,act,cerr,can,ventas from public.pedidos where timezone('America/Guayaquil',creado_en)::date=f;
 select coalesce(sum(pg.monto),0) into pagado from public.pagos pg join public.pedidos p on p.id=pg.pedido_id
 where timezone('America/Guayaquil',pg.registrado_en)::date=f and pg.anulado=false and p.estado<>'cancelado';
 return jsonb_build_object('fecha',f,'total_pedidos',tot,'pedidos_activos',act,'pedidos_cerrados',cerr,'pedidos_cancelados',can,
 'ventas_generadas',round(ventas,2),'total_pagado',round(pagado,2));
end $$;
revoke all on function public.resumen_diario(date) from public;
grant execute on function public.resumen_diario(date) to authenticated;

