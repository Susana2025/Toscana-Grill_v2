do $$ begin create type public.rol_usuario as enum ('administrador','caja','cocina','mesero'); exception when duplicate_object then null; end $$;
do $$ begin create type public.estado_pedido as enum ('pendiente','confirmado','en_preparacion','listo','entregado','cerrado','cancelado'); exception when duplicate_object then null; end $$;
do $$ begin create type public.tipo_pedido as enum ('mesa','para_llevar','delivery'); exception when duplicate_object then null; end $$;
do $$ begin create type public.estado_pago as enum ('pendiente','pagado','anulado'); exception when duplicate_object then null; end $$;
