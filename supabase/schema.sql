create or replace function public.registrar_historial_estado() returns trigger
language plpgsql security definer set search_path='' as $$
begin
 if tg_op='INSERT' then
   insert into public.historial_estado_pedido(pedido_id,estado_anterior,estado_nuevo,cambiado_por)
   values(new.id,null,new.estado,auth.uid());
 elsif old.estado is distinct from new.estado then
   insert into public.historial_estado_pedido(pedido_id,estado_anterior,estado_nuevo,cambiado_por)
   values(new.id,old.estado,new.estado,auth.uid());
 end if;
 return new;
end $$;
drop trigger if exists pedido_historial_insert on public.pedidos;
create trigger pedido_historial_insert after insert on public.pedidos for each row execute function public.registrar_historial_estado();
drop trigger if exists pedido_historial_update on public.pedidos;
